create_file "scripts/benchmark/validate_paper_results.py" '#!/usr/bin/env python3
"""Validate paper-results manifest fields, uniqueness, and provenance paths."""
from __future__ import annotations

import os
import shutil
import sys
from pathlib import Path


def _load_yaml():
    try:
        import yaml
        return yaml
    except ModuleNotFoundError:
        exp = shutil.which("exp")
        if exp:
            launcher = Path(exp).resolve()
            shebang = launcher.read_text().splitlines()[0]
            interpreter = shebang[2:] if shebang.startswith("#!") else ""
            if (
                shebang.startswith("#!")
                and Path(interpreter).exists()
                and Path(sys.executable) != Path(interpreter)
            ):
                os.execv(interpreter, [interpreter, __file__, *sys.argv[1:]])
        print(
            "[error] PyYAML is unavailable; install the exp-registry CLI first",
            file=sys.stderr,
        )
        raise SystemExit(2)


yaml = _load_yaml()

MANIFEST = Path("docs/paper-results/results.yaml")
REQUIRED_FIELDS = (
    "paper_key",
    "exp_id",
    "benchmark",
    "value",
    "source_registry",
    "source_output",
    "status",
    "date",
)


def main() -> int:
    if not MANIFEST.exists():
        print(f"[error] {MANIFEST} not found", file=sys.stderr)
        return 1

    data = yaml.safe_load(MANIFEST.read_text()) or {}
    entries = data.get("results") or []
    if not entries:
        print(f"[warn] {MANIFEST} has no results entries")
        return 0

    errors: list[str] = []
    seen_keys: set[str] = set()
    for idx, entry in enumerate(entries):
        prefix = f"entry[{idx}]"
        if not isinstance(entry, dict):
            errors.append(f"{prefix}: not a mapping")
            continue
        for field in REQUIRED_FIELDS:
            if field not in entry:
                errors.append(f"{prefix}: missing field {field!r}")
        key = entry.get("paper_key")
        if key in seen_keys:
            errors.append(f"{prefix}: duplicate paper_key {key!r}")
        elif key:
            seen_keys.add(key)
        for path_field in ("source_registry", "source_output"):
            source = entry.get(path_field)
            if source and not Path(source).exists():
                errors.append(
                    f"{prefix}: {path_field} {source!r} does not exist"
                )

    if errors:
        print("[fail] manifest validation errors:", file=sys.stderr)
        for error in errors:
            print(f"  - {error}", file=sys.stderr)
        return 1

    print(f"[ok] {len(entries)} entries validated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'

create_file "scripts/benchmark/generate_paper_results.py" '#!/usr/bin/env python3
"""Generate LaTeX result macros from docs/paper-results/results.yaml."""
from __future__ import annotations

import os
import re
import shutil
import sys
from pathlib import Path


def _load_yaml():
    try:
        import yaml
        return yaml
    except ModuleNotFoundError:
        exp = shutil.which("exp")
        if exp:
            launcher = Path(exp).resolve()
            shebang = launcher.read_text().splitlines()[0]
            interpreter = shebang[2:] if shebang.startswith("#!") else ""
            if (
                shebang.startswith("#!")
                and Path(interpreter).exists()
                and Path(sys.executable) != Path(interpreter)
            ):
                os.execv(interpreter, [interpreter, __file__, *sys.argv[1:]])
        print(
            "[error] PyYAML is unavailable; install the exp-registry CLI first",
            file=sys.stderr,
        )
        raise SystemExit(2)


yaml = _load_yaml()

MANIFEST = Path("docs/paper-results/results.yaml")
OUTPUT = Path("paper/generated/results_macros.tex")


def _macro_name(paper_key: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", paper_key)
    return "Result" + "".join(part.capitalize() for part in parts if part)


def main() -> int:
    if not MANIFEST.exists():
        print(f"[error] {MANIFEST} not found", file=sys.stderr)
        return 1
    data = yaml.safe_load(MANIFEST.read_text()) or {}
    entries = data.get("results") or []
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "% Auto-generated from docs/paper-results/results.yaml",
        "% DO NOT EDIT BY HAND",
        "",
    ]
    written = 0
    for entry in entries:
        if not isinstance(entry, dict):
            continue
        key = entry.get("paper_key")
        value = entry.get("value")
        if key is None or value is None:
            continue
        lines.append(f"\\providecommand{{\\{_macro_name(key)}}}{{{value}}}")
        written += 1
    lines.append("")
    OUTPUT.write_text("\n".join(lines))
    print(f"[ok] wrote {written} macros to {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'

