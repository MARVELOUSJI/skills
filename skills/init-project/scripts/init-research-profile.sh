`results.yaml` is the paper-facing source of truth for benchmark numbers. Raw
outputs remain in `outputs/`, and full experiment history remains in
`docs/experiment-registry/registry/`.

## Three-tier sources of truth

1. **Raw outputs** (`outputs/`) — immutable evidence
2. **Experiment registry** (`docs/experiment-registry/registry/*.yaml`) — full
   history, including diagnostic, stale, and canonical runs
3. **Paper manifest** (`docs/paper-results/results.yaml`) — the canonical subset
   allowed into paper tables and prose

## Workflow

```bash
python3 scripts/benchmark/validate_paper_results.py
python3 scripts/benchmark/generate_paper_results.py
```

Paper tables and prose should reference generated macros rather than
hand-written numbers.

## Entry schema

```yaml
- paper_key: "main_table.method_a.benchmark_x"
  exp_id: exp01a
  benchmark: benchmark_x
  eval_mode: agent
  value: 73.50
  correct: 1234
  total: 1678
  source_registry: docs/experiment-registry/registry/exp01a.yaml
  source_output: outputs/exp01a/benchmark_x/results.json
  status: canonical
  date: YYYY-MM-DD
  notes: |
    Provenance and audit notes
```

Each `paper_key` must identify exactly one canonical number. If the manifest
and registry differ, explain the reason in `notes`.'

